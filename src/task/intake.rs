//! Durable task intake ledger (PQTH - Priority Queue Task Hub).
//!
//! This module implements the ensuring layer between lexical intent detection
//! (M2) and the task subsystem. It provides:
//! - Receipts: durable record of every intake event (source_kind, revision, digest)
//! - Candidates: pending task proposals with review_state and disposition
//! - Transactional creation + CAS resolution
//! - Explicit zeros in all list responses
//! - No mesh travel, no task status expansion, no extraction exemption

use crate::task::intent::detect_task_intents;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::sync::Arc;

/// Source kind for an intake receipt.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SourceKind {
    /// Detected from conversation text via M2 lexical detector
    Conversation,
    /// Explicitly submitted by an agent/user
    Manual,
    /// Imported from external system (git, issue tracker, etc.)
    Imported,
    /// Generated by a tool or automation
    Tool,
}

/// Review state of a candidate.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ReviewState {
    /// Newly created, awaiting triage
    Pending,
    /// Under active review
    InReview,
    /// Accepted - will become a task
    Accepted,
    /// Rejected - dismissed
    Dismissed,
}

/// Final disposition of a candidate.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Disposition {
    /// Still pending resolution
    Pending,
    /// Converted to a task (task_id recorded)
    Created,
    /// Linked to existing task (task_id recorded)
    Linked,
    /// Dismissed without creating a task
    Dismissed,
}

impl std::fmt::Display for Disposition {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Disposition::Pending => write!(f, "pending"),
            Disposition::Created => write!(f, "created"),
            Disposition::Linked => write!(f, "linked"),
            Disposition::Dismissed => write!(f, "dismissed"),
        }
    }
}

/// An intake receipt - immutable record of an intake event.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IntakeReceipt {
    pub id: String,
    pub namespace: String,
    pub source_kind: SourceKind,
    pub source_revision: String,
    pub source_digest: String,
    pub detected_intents: Vec<DetectedIntent>,
    pub raw_text: String,
    pub created_at: String,
}

/// A detected intent from M2 lexical analysis.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DetectedIntent {
    pub marker: String,
    pub excerpt: String,
}

/// A candidate task proposal awaiting resolution.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IntakeCandidate {
    pub id: String,
    pub namespace: String,
    pub receipt_id: String,
    pub title: String,
    pub description: Option<String>,
    pub review_state: ReviewState,
    pub disposition: Disposition,
    pub task_id: Option<String>,
    pub cas_version: u64,
    pub created_at: String,
    pub updated_at: String,
    #[serde(default = "default_candidate_kind")]
    pub candidate_kind: String,
    #[serde(default)]
    pub payload: Value,
    #[serde(default)]
    pub confidence: Option<f64>,
    #[serde(default)]
    pub source_span: Option<Value>,
    #[serde(default)]
    pub extractor_fingerprint: Option<String>,
}

fn default_candidate_kind() -> String {
    "task".to_string()
}

/// Request to create an intake receipt.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CreateReceiptRequest {
    pub namespace: String,
    pub source_kind: SourceKind,
    pub source_revision: String,
    pub source_digest: String,
    pub text: String,
    /// Optional explicit title/description override (for manual intake)
    pub title: Option<String>,
    pub description: Option<String>,
    /// Optional candidate kind override (rule/task/etc.)
    #[serde(default)]
    pub candidate_kind: Option<String>,
    /// Optional payload for the candidate.
    #[serde(default)]
    pub payload: Option<serde_json::Value>,
    /// Optional confidence score.
    #[serde(default)]
    pub confidence: Option<f64>,
    /// Optional source span (e.g. `{"start": 0, "end": 42}`).
    #[serde(default)]
    pub source_span: Option<serde_json::Value>,
    /// Optional extractor fingerprint identifying the extraction mechanism.
    #[serde(default)]
    pub extractor_fingerprint: Option<String>,
}

/// Request to list receipts.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ListReceiptsRequest {
    pub namespace: String,
    pub limit: Option<usize>,
    pub offset: Option<usize>,
}

/// Request to list candidates.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ListCandidatesRequest {
    pub namespace: String,
    pub review_state: Option<ReviewState>,
    pub disposition: Option<Disposition>,
    pub limit: Option<usize>,
    pub offset: Option<usize>,
}

/// Request to resolve a candidate.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ResolveCandidateRequest {
    pub namespace: String,
    pub candidate_id: String,
    pub disposition: Disposition,
    pub task_id: Option<String>,
    /// CAS version for optimistic concurrency
    pub cas_version: u64,
}

/// Response for list operations with explicit zeros.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IntakeListResponse<T> {
    pub namespace: String,
    pub count: usize,
    pub total: usize,
    pub offset: usize,
    pub limit: usize,
    pub items: Vec<T>,
}

/// Result of creating a receipt with candidate(s).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CreateReceiptResult {
    pub receipt: IntakeReceipt,
    pub candidates: Vec<IntakeCandidate>,
    /// Always present, zero when no candidates created
    pub candidate_count: usize,
}

/// Result of resolving a candidate.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ResolveCandidateResult {
    pub candidate: IntakeCandidate,
    pub task_created: bool,
    pub task_id: Option<String>,
}


/// Generate a deterministic ID for a receipt.
/// Uses SHA-256 (not `DefaultHasher`, which is toolchain-unstable) so the
/// persisted MERGE keys survive Rust version changes.
pub fn generate_receipt_id(namespace: &str, source_digest: &str) -> String {
    use sha2::{Digest, Sha256};
    let mut hasher = Sha256::new();
    hasher.update(namespace.as_bytes());
    hasher.update([0u8]);
    hasher.update(source_digest.as_bytes());
    let digest = hasher.finalize();
    format!("rcpt-{:016x}", u64::from_be_bytes(digest[..8].try_into().unwrap()))
}

/// Generate a deterministic ID for a candidate (SHA-256, toolchain-stable).
fn generate_candidate_id(namespace: &str, receipt_id: &str, index: usize) -> String {
    use sha2::{Digest, Sha256};
    let mut hasher = Sha256::new();
    hasher.update(namespace.as_bytes());
    hasher.update([0u8]);
    hasher.update(receipt_id.as_bytes());
    hasher.update([0u8]);
    hasher.update(index.to_le_bytes());
    let digest = hasher.finalize();
    format!("cand-{:016x}", u64::from_be_bytes(digest[..8].try_into().unwrap()))
}

/// Extract title from text using heuristics.
fn extract_title(text: &str) -> String {
    // First line, capped at 120 chars
    let first_line = text.lines().next().unwrap_or(text);
    let title = first_line.trim();
    if title.chars().count() > 120 {
        title.chars().take(120).collect()
    } else {
        title.to_string()
    }
}

/// Create candidates from detected intents.
pub fn create_candidates_from_intents(
    namespace: &str,
    receipt_id: &str,
    request: &CreateReceiptRequest,
    intents: Vec<DetectedIntent>,
) -> Vec<IntakeCandidate> {
    // Explicit title wins: one deterministic candidate, no M2 re-splitting.
    if let Some(title) = request.title.clone() {
        let now = chrono::Utc::now().format("%Y-%m-%dT%H:%M:%SZ").to_string();
        let candidate_kind = request.candidate_kind.clone().unwrap_or_else(|| {
            if title.starts_with("[rule_candidate]") { "rule".to_string() } else { "task".to_string() }
        });
        return vec![IntakeCandidate {
            id: generate_candidate_id(namespace, receipt_id, 0),
            namespace: namespace.to_string(),
            receipt_id: receipt_id.to_string(),
            title,
            description: request.description.clone(),
            review_state: ReviewState::Pending,
            disposition: Disposition::Pending,
            task_id: None,
            cas_version: 1,
            created_at: now.clone(),
            updated_at: now,
            candidate_kind,
            payload: request.payload.clone().unwrap_or(serde_json::Value::Null),
            confidence: request.confidence,
            source_span: request.source_span.clone().or_else(|| {
                Some(serde_json::json!({"start": 0, "end": request.text.len()}))
            }),
            extractor_fingerprint: request
                .extractor_fingerprint
                .clone()
                .or_else(|| Some("manual-override-v1".to_string())),
        }];
    }

    let mut candidates = Vec::new();

    if intents.is_empty() {
        // No intents detected - create a single candidate from the raw text
        let now = chrono::Utc::now().format("%Y-%m-%dT%H:%M:%SZ").to_string();
        let title = request.title.clone().unwrap_or_else(|| extract_title(&request.text));
        let description = request.description.clone().or_else(|| {
            if request.text.len() > title.len() {
                Some(request.text.clone())
            } else {
                None
            }
        });
        candidates.push(IntakeCandidate {
            id: generate_candidate_id(namespace, receipt_id, 0),
            namespace: namespace.to_string(),
            receipt_id: receipt_id.to_string(),
            title,
            description,
            review_state: ReviewState::Pending,
            disposition: Disposition::Pending,
            task_id: None,
            cas_version: 1,
            created_at: now.clone(),
            updated_at: now,
            candidate_kind: request.candidate_kind.clone().unwrap_or_else(|| "task".to_string()),
            payload: request.payload.clone().unwrap_or(serde_json::Value::Null),
            confidence: request.confidence,
            source_span: request.source_span.clone().or_else(|| {
                Some(serde_json::json!({"start": 0, "end": request.text.len()}))
            }),
            extractor_fingerprint: request
                .extractor_fingerprint
                .clone()
                .or_else(|| Some("raw-text-fallback-v1".to_string())),
        });
    } else {
        // Create one candidate per distinct intent
        for (i, intent) in intents.into_iter().enumerate() {
            let now = chrono::Utc::now().format("%Y-%m-%dT%H:%M:%SZ").to_string();
            let title = format!("[{}] {}", intent.marker, intent.excerpt.chars().take(80).collect::<String>());
            let span = request.source_span.clone().or_else(|| {
                request
                    .text
                    .find(&intent.excerpt)
                    .map(|start| serde_json::json!({"start": start, "end": start + intent.excerpt.len()}))
                    .or_else(|| Some(serde_json::json!({"start": 0, "end": request.text.len()})))
            });
            let fp = request
                .extractor_fingerprint
                .clone()
                .or_else(|| Some(format!("lexical-intent:{}", intent.marker)));
            candidates.push(IntakeCandidate {
                id: generate_candidate_id(namespace, receipt_id, i),
                namespace: namespace.to_string(),
                receipt_id: receipt_id.to_string(),
                title,
                description: Some(request.text.clone()),
                review_state: ReviewState::Pending,
                disposition: Disposition::Pending,
                task_id: None,
                cas_version: 1,
                created_at: now.clone(),
                updated_at: now,
                candidate_kind: request.candidate_kind.clone().unwrap_or_else(|| "task".to_string()),
                payload: request.payload.clone().unwrap_or(serde_json::Value::Null),
                confidence: request.confidence,
                source_span: span,
                extractor_fingerprint: fp,
            });
        }
    }

    candidates
}

/// Process intake text and return detected intents.
pub fn process_intake_text(text: &str) -> Vec<DetectedIntent> {
    let signals = detect_task_intents(text);
    signals
        .into_iter()
        .map(|s| DetectedIntent {
            marker: s.marker.to_string(),
            excerpt: s.excerpt,
        })
        .collect()
}

