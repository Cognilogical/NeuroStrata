    use super::*;

    #[test]
    fn test_generate_receipt_id_deterministic() {
        let id1 = generate_receipt_id("test-ns", "abc123");
        let id2 = generate_receipt_id("test-ns", "abc123");
        assert_eq!(id1, id2);
    }

