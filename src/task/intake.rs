/// Handler for neurostrata_task_intake tool.
pub async fn handle_intake(
    args: Value,
    store: Arc<dyn crate::traits::VectorStore>,
) -> String {
    use crate::traits::IntakeStore;

    // Parse arguments
    let namespace = match args.get("namespace").and_then(|v| v.as_str()) {
        Some(n) if !n.trim().is_empty() => n.to_string(),
        _ => return "ERROR: 'namespace' is required and cannot be empty.".to_string(),
    };

    let source_kind = match args.get("source_kind").and_then(|v| v.as_str()) {
        Some("manual") => SourceKind::Manual,
        Some("imported") => SourceKind::Imported,
        Some("tool") => SourceKind::Tool,
        _ => SourceKind::Conversation, // default
    };

    let source_revision = match args.get("source_revision").and_then(|v| v.as_str()) {
        Some(s) if !s.trim().is_empty() => s.to_string(),
        _ => return "ERROR: 'source_revision' is required and cannot be empty.".to_string(),
    };

    let source_digest = match args.get("source_digest").and_then(|v| v.as_str()) {
        Some(s) if !s.trim().is_empty() => s.to_string(),
        _ => return "ERROR: 'source_digest' is required and cannot be empty.".to_string(),
    };

    let text = match args.get("text").and_then(|v| v.as_str()) {
        Some(t) if !t.trim().is_empty() => t.to_string(),
        _ => return "ERROR: 'text' is required and cannot be empty.".to_string(),
    };

    let title = args.get("title").and_then(|v| v.as_str()).map(|s| s.to_string());
    let description = args.get("description").and_then(|v| v.as_str()).map(|s| s.to_string());

    // Downcast to IntakeStore
    let intake_store = match store.as_any().downcast_ref::<crate::store::ladybug::LadybugStore>() {
        Some(s) => s,
        None => return "ERROR: Intake requires LadybugStore backend.".to_string(),
    };

    let request = CreateReceiptRequest {
        namespace: namespace.clone(),
        source_kind,
        source_revision,
        source_digest,
        text,
        title,
        description,
    };

    match intake_store.create_receipt(request).await {
        Ok(result) => {
            let response = serde_json::json!({
                "receipt": result.receipt,
                "candidates": result.candidates,
                "candidate_count": result.candidate_count,
            });
            serde_json::to_string_pretty(&response).unwrap_or_else(|e| format!("ERROR: {}", e))
        }
        Err(e) => e,
    }
}

/// Handler for neurostrata_task_intake_list tool.
pub async fn handle_intake_list(
    args: Value,
    store: Arc<dyn crate::traits::VectorStore>,
) -> String {
    use crate::traits::IntakeStore;

    let namespace = match args.get("namespace").and_then(|v| v.as_str()) {
        Some(n) if !n.trim().is_empty() => n.to_string(),
        _ => return "ERROR: 'namespace' is required and cannot be empty.".to_string(),
    };

    let mode = args.get("mode").and_then(|v| v.as_str()).unwrap_or("candidates");

    let intake_store = match store.as_any().downcast_ref::<crate::store::ladybug::LadybugStore>() {
        Some(s) => s,
        None => return "ERROR: Intake requires LadybugStore backend.".to_string(),
    };

    match mode {
        "receipts" => {
            let limit = args.get("limit").and_then(|v| v.as_u64()).map(|v| v as usize);
            let offset = args.get("offset").and_then(|v| v.as_u64()).map(|v| v as usize);

            let request = ListReceiptsRequest {
                namespace: namespace.clone(),
                limit,
                offset,
            };

            match intake_store.list_receipts(request).await {
                Ok(response) => {
                    let result = serde_json::json!({
                        "namespace": response.namespace,
                        "count": response.count,
                        "total": response.total,
                        "offset": response.offset,
                        "limit": response.limit,
                        "receipts": response.items,
                    });
                    serde_json::to_string_pretty(&result).unwrap_or_else(|e| format!("ERROR: {}", e))
                }
                Err(e) => e,
            }
        }
        "candidates" => {
            let limit = args.get("limit").and_then(|v| v.as_u64()).map(|v| v as usize);
            let offset = args.get("offset").and_then(|v| v.as_u64()).map(|v| v as usize);

            let review_state = args.get("review_state").and_then(|v| v.as_str()).and_then(|s| match s {
                "pending" => Some(ReviewState::Pending),
                "in_review" => Some(ReviewState::InReview),
                "accepted" => Some(ReviewState::Accepted),
                "dismissed" => Some(ReviewState::Dismissed),
                _ => None,
            });

            let disposition = args.get("disposition").and_then(|v| v.as_str()).and_then(|s| match s {
                "pending" => Some(Disposition::Pending),
                "created" => Some(Disposition::Created),
                "linked" => Some(Disposition::Linked),
                "dismissed" => Some(Disposition::Dismissed),
                _ => None,
            });

            let request = ListCandidatesRequest {
                namespace: namespace.clone(),
                review_state,
                disposition,
                limit,
                offset,
            };

            match intake_store.list_candidates(request).await {
                Ok(response) => {
                    let result = serde_json::json!({
                        "namespace": response.namespace,
                        "count": response.count,
                        "total": response.total,
                        "offset": response.offset,
                        "limit": response.limit,
                        "candidates": response.items,
                    });
                    serde_json::to_string_pretty(&result).unwrap_or_else(|e| format!("ERROR: {}", e))
                }
                Err(e) => e,
            }
        }
        _ => "ERROR: 'mode' must be 'receipts' or 'candidates'.".to_string(),
    }
}

/// Handler for neurostrata_task_intake_resolve tool.
pub async fn handle_intake_resolve(
    args: Value,
    store: Arc<dyn crate::traits::VectorStore>,
) -> String {
    use crate::traits::IntakeStore;

    let namespace = match args.get("namespace").and_then(|v| v.as_str()) {
        Some(n) if !n.trim().is_empty() => n.to_string(),
        _ => return "ERROR: 'namespace' is required and cannot be empty.".to_string(),
    };

    let candidate_id = match args.get("candidate_id").and_then(|v| v.as_str()) {
        Some(s) if !s.trim().is_empty() => s.to_string(),
        _ => return "ERROR: 'candidate_id' is required and cannot be empty.".to_string(),
    };

    let disposition = match args.get("disposition").and_then(|v| v.as_str()) {
        Some("created") => Disposition::Created,
        Some("linked") => Disposition::Linked,
        Some("dismissed") => Disposition::Dismissed,
        _ => return "ERROR: 'disposition' must be 'created', 'linked', or 'dismissed'.".to_string(),
    };

    let task_id = args.get("task_id").and_then(|v| v.as_str()).map(|s| s.to_string());

    // Validate task_id is provided for created/linked dispositions
    if (disposition == Disposition::Created || disposition == Disposition::Linked) && task_id.is_none() {
        return format!("ERROR: 'task_id' is required when disposition is '{}'.", disposition);
    }

    let cas_version = match args.get("cas_version").and_then(|v| v.as_u64()) {
        Some(v) => v,
        None => return "ERROR: 'cas_version' is required (u64).".to_string(),
    };

    let intake_store = match store.as_any().downcast_ref::<crate::store::ladybug::LadybugStore>() {
        Some(s) => s,
        None => return "ERROR: Intake requires LadybugStore backend.".to_string(),
    };

    let request = ResolveCandidateRequest {
        namespace: namespace.clone(),
        candidate_id,
        disposition,
        task_id,
        cas_version,
    };

    match intake_store.resolve_candidate(request).await {
        Ok(result) => {
            let response = serde_json::json!({
                "candidate": result.candidate,
                "task_created": result.task_created,
                "task_id": result.task_id,
            });
            serde_json::to_string_pretty(&response).unwrap_or_else(|e| format!("ERROR: {}", e))
        }
        Err(e) => e,
    }
}

